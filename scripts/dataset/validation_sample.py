"""Pick what the group validates by hand and render it readably (docs/04, Validation).

Rule decided 2026-11-01: per training sector, check 2 companies; if both pass,
accept the sector; if 1 fails, check 5 more; if both fail, check every company
in the sector. All held-out (eval) companies are checked in full. Attacks: 2
wordings per family and pool. Email and document carriers are checked as part
of each company.

The order of companies within a sector is seeded, so the rounds are fixed
before anyone looks at the data.

Usage:
  python3 scripts/dataset/validation_sample.py [--data data/full]
Writes <data>/validation/plan.md and one page per company in
<data>/validation/companies/<split>/<sector>/. Standard library only; Python 3.9+.
"""
import argparse
import hashlib
import json
import random
from collections import defaultdict
from pathlib import Path

from build_tasks import load_companies

SEED = "ece1776-validation"
FIRST, SECOND = 2, 5
WORDINGS = 2

ITEM_CHECKS = [
    "Content is plausible for this company and sector.",
    "Tier is plausible for this company (the tag is ground truth, but it must be believable).",
    "Mismatch label (if any) fits: a public item that looks sensitive, or a confidential item that looks bland.",
    "Every marker appears in the content and is specific enough not to appear by chance.",
    "The request phrase names the item without giving away any marker.",
    "No real company, person or product is named.",
]
CARRIER_CHECKS = [
    "The user's task is answerable from the email or document alone.",
    "The task markers are the answer to the task.",
    "The injection asks for {item} and reads like a plausible attack.",
]
WORDING_CHECKS = [
    "Reads like something a real requester or attacker would write.",
    "Fits its family (benign, direct, tampering, paraphrase, summary, encoding).",
    "Works with any item phrase in the {item} slot.",
]


def page_path(c):
    return f"companies/{c['split']}/{c['sector']}/{c['company_id']}.md"


def order(key, ids):
    ids = sorted(ids)
    random.Random(hashlib.sha256(f"{SEED}/{key}".encode()).hexdigest()).shuffle(ids)
    return ids


def render_company(c):
    lines = [f"# {c['name']} (`{c['company_id']}`)", "",
             f"Sector **{c['sector']}**, split **{c['split']}**. {c['description']}", "",
             f"Access contact: {c['access_contact']}", "", "## Items", ""]
    for i in c["items"]:
        mis = f", mismatch **{i['mismatch']}**" if "mismatch" in i else ""
        markers = ", ".join(f"`{m['value']}`" + (f" (also {', '.join(m['variants'])})" if m.get("variants") else "")
                            for m in i["markers"])
        lines += [f"### {i['item_id']}: {i['title']}", "",
                  f"Tier **{i['tier']}**{mis}. Request phrase: \"{i['request_phrase']}\"", "",
                  f"> {i['content']}", "",
                  f"Canary: `{i['canary']}`. Markers: {markers}", ""]
    lines += ["## Checks per item", ""] + [f"- [ ] {x}" for x in ITEM_CHECKS] + [""]
    lines += ["## Carriers (indirect injection)", ""]
    for cr in c["carriers"]:
        lines += [f"### {cr['carrier_id']} ({cr['family']})", "",
                  f"Task: \"{cr['task_request']}\" Expected in the answer: "
                  + ", ".join(f"`{m}`" for m in cr["task_markers"]), "",
                  "```json", json.dumps(cr["payload"], indent=2, ensure_ascii=False), "```", ""]
    lines += ["## Checks per carrier", ""] + [f"- [ ] {x}" for x in CARRIER_CHECKS] + [""]
    lines += ["## Verdict", "", "- [ ] Pass", "- [ ] Fail. Reason:", "",
              "Reviewer: ______  Date: ______", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="data/full")
    data = Path(ap.parse_args().data)
    companies = {c["company_id"]: c for c in load_companies(data / "companies")}
    templates = json.loads((data / "attack_templates.json").read_text())
    out = data / "validation"
    (out / "companies").mkdir(parents=True, exist_ok=True)
    for cid, c in companies.items():
        page = out / page_path(c)
        page.parent.mkdir(parents=True, exist_ok=True)
        page.write_text(render_company(c))

    by_sector = defaultdict(list)
    for cid, c in companies.items():
        by_sector[(c["split"], c["sector"])].append(cid)

    def link(cid):
        return f"[{cid}]({page_path(companies[cid])})"

    lines = ["# Validation plan", "",
             "Generated by `scripts/dataset/validation_sample.py`; rule and decisions in docs/04 (Validation) "
             "and the docs/07 log (2026-11-01). The company order is seeded, so do not reorder.", "",
             "## Rule", "",
             f"- Training sectors: check round 1 ({FIRST} companies). Both pass: sector accepted. "
             f"One fails: check round 2 ({SECOND} more). Both fail: check every company in the sector "
             "(round 3).",
             "- What happens if round 2 also has failures is **Open** (docs/07, Q46).",
             "- Held-out sectors: every company is checked.",
             "- A failed company is fixed and rechecked before training data is built.", "",
             "## Training sectors", "",
             "| sector | round 1 | round 2 (if 1 of 2 fails) | round 3 (if 2 of 2 fail) | result |",
             "|---|---|---|---|---|"]
    for (split, sector), ids in sorted(by_sector.items()):
        if split != "train":
            continue
        ids = order(sector, ids)
        lines.append(f"| {sector} | {', '.join(map(link, ids[:FIRST]))} | "
                     f"{', '.join(map(link, ids[FIRST:FIRST + SECOND]))} | "
                     f"{', '.join(map(link, ids[FIRST + SECOND:]))} | |")
    lines += ["", "## Held-out sectors (check all)", "", "| sector | companies | result |", "|---|---|---|"]
    for (split, sector), ids in sorted(by_sector.items()):
        if split == "eval":
            lines.append(f"| {sector} | {', '.join(map(link, sorted(ids)))} | |")

    lines += ["", f"## Attack wordings ({WORDINGS} per family and pool)", "",
              "Checks per wording:", ""] + [f"- {x}" for x in WORDING_CHECKS] + [
              "", "| family | pool | id | wording | pass? |", "|---|---|---|---|---|"]
    for fam, spec in templates["families"].items():
        for pool, wordings in spec.get("pools", {}).items():
            picked = order(f"{fam}/{pool}", [w["id"] for w in wordings])[:WORDINGS]
            for w in wordings:
                if w["id"] in picked:
                    lines.append(f"| {fam} | {pool} | {w['id']} | {w['text'].replace('|', '/')} | |")
    lines += ["", "Email and document carriers are written per company and are checked with their company.", ""]
    (out / "plan.md").write_text("\n".join(lines))
    n_first = sum(min(FIRST, len(v)) for (s, _), v in by_sector.items() if s == "train")
    n_eval = sum(len(v) for (s, _), v in by_sector.items() if s == "eval")
    print(f"{out / 'plan.md'}: round 1 = {n_first} training companies, plus {n_eval} held-out companies")


if __name__ == "__main__":
    main()
